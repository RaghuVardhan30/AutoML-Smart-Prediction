from pathlib import Path
import json

import numpy as np
import pandas as pd

from sklearn.model_selection import train_test_split
from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score
)

from pycaret.regression import (
    setup,
    compare_models,
    tune_model,
    finalize_model,
    save_model,
    predict_model
)


# =========================================================
# PROJECT PATHS
# =========================================================

PROJECT_ROOT = Path(__file__).resolve().parent.parent

DATA_PATH = (
    PROJECT_ROOT
    / "data"
    / "processed"
    / "processed_data.csv"
)

MODEL_PATH = (
    PROJECT_ROOT
    / "models"
    / "best_model"
)

RESULTS_DIR = (
    PROJECT_ROOT
    / "models"
)

METRICS_PATH = (
    RESULTS_DIR
    / "evaluation_metrics.json"
)

PREDICTIONS_PATH = (
    RESULTS_DIR
    / "test_predictions.csv"
)


# =========================================================
# MAIN
# =========================================================

def main():

    print("=" * 60)
    print("AUTOML SMART PREDICTION SYSTEM")
    print("=" * 60)

    # -----------------------------------------------------
    # 1. Load processed dataset
    # -----------------------------------------------------

    print("\n[1] Loading processed dataset...")

    df = pd.read_csv(DATA_PATH)

    print(f"Dataset shape: {df.shape}")

    print("\nTarget variable: G3")

    # -----------------------------------------------------
    # 2. Separate features and target
    # -----------------------------------------------------

    X = df.drop(columns=["G3"])
    y = df["G3"]

    print(f"\nFeatures: {X.shape[1]}")
    print(f"Target samples: {len(y)}")

    # -----------------------------------------------------
    # 3. Train-Test Split
    # -----------------------------------------------------

    print("\n[2] Splitting dataset...")

    X_train, X_test, y_train, y_test = train_test_split(
        X,
        y,
        test_size=0.20,
        random_state=42
    )

    print(f"Training samples: {len(X_train)}")
    print(f"Testing samples : {len(X_test)}")

    # -----------------------------------------------------
    # 4. Create training dataframe
    # -----------------------------------------------------

    train_data = X_train.copy()

    train_data["G3"] = y_train.values

    # -----------------------------------------------------
    # 5. AutoML Setup
    # -----------------------------------------------------

    print("\n[3] Initializing AutoML...")

    categorical_features = [
        "school",
        "sex",
        "address",
        "famsize",
        "Pstatus",
        "Mjob",
        "Fjob",
        "reason",
        "guardian",
        "schoolsup",
        "famsup",
        "paid",
        "activities",
        "nursery",
        "higher",
        "internet",
    ]

    automl_setup = setup(
        data=train_data,
        target="G3",

        session_id=42,

        categorical_features=categorical_features,

        normalize=True,
        normalize_method= "zscore",

        fold=10,

        verbose=True
    )

    # -----------------------------------------------------
    # 6. Compare Models
    # -----------------------------------------------------

    print("\n[4] Comparing machine learning models...")

    best_model = compare_models(
        sort="RMSE"
    )

    print("\n" + "=" * 60)
    print("BEST MODEL FROM AUTOML")
    print("=" * 60)

    print(best_model)

    # -----------------------------------------------------
    # 7. Tune Best Model
    # -----------------------------------------------------

    print("\n[5] Tuning best model...")

    tuned_model = tune_model(
        best_model,
        optimize="RMSE"
    )

    print("\nTuned model:")
    print(tuned_model)

    # -----------------------------------------------------
    # 8. Predict on unseen test data
    # -----------------------------------------------------

    print("\n[6] Evaluating model on unseen test data...")

    test_data = X_test.copy()

    test_data["G3"] = y_test.values

    predictions = predict_model(
        tuned_model,
        data=test_data
    )

    # PyCaret normally stores predictions in "prediction_label"
    prediction_column = "prediction_label"

    if prediction_column not in predictions.columns:
        raise ValueError(
            "Prediction column was not generated by PyCaret."
        )

    y_pred = predictions[prediction_column].values

    # -----------------------------------------------------
    # 9. Calculate evaluation metrics
    # -----------------------------------------------------

    mae = mean_absolute_error(
        y_test,
        y_pred
    )

    mse = mean_squared_error(
        y_test,
        y_pred
    )

    rmse = np.sqrt(mse)

    r2 = r2_score(
        y_test,
        y_pred
    )

    print("\n" + "=" * 60)
    print("TEST SET EVALUATION")
    print("=" * 60)

    print(f"MAE  : {mae:.4f}")
    print(f"MSE  : {mse:.4f}")
    print(f"RMSE : {rmse:.4f}")
    print(f"R²   : {r2:.4f}")

    # -----------------------------------------------------
    # 10. Save evaluation metrics
    # -----------------------------------------------------

    RESULTS_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    metrics = {
        "model": str(tuned_model),
        "test_samples": int(len(y_test)),
        "mae": float(mae),
        "mse": float(mse),
        "rmse": float(rmse),
        "r2": float(r2)
    }

    with open(
        METRICS_PATH,
        "w",
        encoding="utf-8"
    ) as file:

        json.dump(
            metrics,
            file,
            indent=4
        )

    print(
        f"\nEvaluation metrics saved to:\n{METRICS_PATH}"
    )

    # -----------------------------------------------------
    # 11. Save test predictions
    # -----------------------------------------------------

    prediction_results = pd.DataFrame({
        "Actual_G3": y_test.values,
        "Predicted_G3": y_pred
    })

    prediction_results["Error"] = (
        prediction_results["Actual_G3"]
        - prediction_results["Predicted_G3"]
    )

    prediction_results.to_csv(
        PREDICTIONS_PATH,
        index=False
    )

    print(
        f"Test predictions saved to:\n{PREDICTIONS_PATH}"
    )

    # -----------------------------------------------------
    # 12. Finalize model
    # -----------------------------------------------------

    print("\n[7] Finalizing model...")

    final_model = finalize_model(
        tuned_model
    )

    # -----------------------------------------------------
    # 13. Save final model
    # -----------------------------------------------------

    save_model(
        final_model,
        str(MODEL_PATH)
    )

    print(
        f"\nFinal model saved to:\n{MODEL_PATH}.pkl"
    )

    # -----------------------------------------------------
    # 14. Display sample predictions
    # -----------------------------------------------------

    print("\n" + "=" * 60)
    print("SAMPLE PREDICTIONS")
    print("=" * 60)

    print(
        prediction_results
        .head(10)
        .to_string(index=False)
    )

    print("\n" + "=" * 60)
    print("AUTOML TRAINING COMPLETED SUCCESSFULLY")
    print("=" * 60)


# =========================================================
# RUN PROGRAM
# =========================================================

if __name__ == "__main__":
    main()